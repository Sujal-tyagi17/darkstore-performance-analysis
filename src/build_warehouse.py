"""
Build the DuckDB warehouse from the raw CSVs and run every SQL analysis query.

  1. sql/00_staging.sql   -> cleaned star schema inside data/darkstore.duckdb
  2. sql/01..NN_*.sql     -> each query result saved to data/processed/<name>.csv
  3. data quality log     -> reports/data_quality.md

Run:  python src/build_warehouse.py
"""

from __future__ import annotations

from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
PROCESSED = ROOT / "data" / "processed"
DB_PATH = ROOT / "data" / "darkstore.duckdb"
SQL_DIR = ROOT / "sql"
REPORTS = ROOT / "reports"


def connect(read_only: bool = False) -> duckdb.DuckDBPyConnection:
    return duckdb.connect(str(DB_PATH), read_only=read_only)


def build_staging(con: duckdb.DuckDBPyConnection) -> None:
    sql = (SQL_DIR / "00_staging.sql").read_text().replace("{raw}", RAW.as_posix())
    con.execute(sql)


def run_analysis_queries(con: duckdb.DuckDBPyConnection) -> dict[str, int]:
    PROCESSED.mkdir(parents=True, exist_ok=True)
    for old in PROCESSED.glob("*.csv"):     # start clean so no stale outputs linger
        old.unlink()
    results = {}
    for path in sorted(SQL_DIR.glob("[0-9][0-9]_*.sql")):
        if path.name.startswith("00_"):
            continue
        name = path.stem[3:]  # drop the "NN_" prefix
        df = con.execute(path.read_text()).df()
        df.to_csv(PROCESSED / f"{name}.csv", index=False)
        results[name] = len(df)
    return results


def write_quality_report(con: duckdb.DuckDBPyConnection) -> None:
    REPORTS.mkdir(parents=True, exist_ok=True)
    log = con.execute("SELECT * FROM data_quality_log").fetchall()
    raw_rows = con.execute("SELECT count(*) FROM raw_orders").fetchone()[0]
    clean_rows = con.execute("SELECT count(*) FROM fact_orders").fetchone()[0]
    valid = con.execute("SELECT count(*) FROM fact_orders WHERE valid_timing").fetchone()[0]
    lines = [
        "# Data quality report",
        "",
        "Generated by `src/build_warehouse.py` from the cleaning rules in `sql/00_staging.sql`.",
        "",
        f"- Raw order rows: **{raw_rows:,}**",
        f"- Clean orders after de-duplication: **{clean_rows:,}**",
        f"- Delivered orders with valid timings (used for speed KPIs): **{valid:,}**",
        "",
        "| Check | Rows affected |",
        "|---|---:|",
    ]
    lines += [f"| {name} | {n:,} |" for name, n in log]
    (REPORTS / "data_quality.md").write_text("\n".join(lines) + "\n")


def build_database() -> None:
    """Build only the DuckDB warehouse (used by the dashboard on first load).

    Leaves data/processed untouched, so the committed analysis outputs stay in place.
    """
    tmp = DB_PATH.with_suffix(".building")
    if tmp.exists():
        tmp.unlink()
    con = duckdb.connect(str(tmp))
    con.execute("SET threads TO 1")
    build_staging(con)
    con.close()
    tmp.replace(DB_PATH)


def main() -> None:
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = connect()
    con.execute("SET threads TO 1")  # single-threaded build: byte-identical outputs on every run
    build_staging(con)
    results = run_analysis_queries(con)
    write_quality_report(con)
    con.close()
    print(f"Warehouse built at {DB_PATH.relative_to(ROOT)}")
    for name, n in results.items():
        print(f"  {name:<28} {n:>6} rows -> data/processed/{name}.csv")


if __name__ == "__main__":
    main()
